const MAP_WIDTH = 1025;
const MAP_HEIGHT = 483;
const MAP_COLUMNS = 100;
const CELL_WIDTH = MAP_WIDTH / MAP_COLUMNS;
const CELL_HEIGHT = MAP_HEIGHT / LAND_MASK.length;

const dots = LAND_MASK.flatMap((row, rowIndex) =>
    [...row].flatMap((cell, columnIndex) => (cell === "#" ? [{ x: (columnIndex + 0.5) * CELL_WIDTH, y: (rowIndex + 0.5) * CELL_HEIGHT }] : [])),
);

/** Longitude/latitude of the offices highlighted on the map. */
